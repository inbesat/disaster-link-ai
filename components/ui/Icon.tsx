// Demo-day hardening · Step 7 — standardized icon wrapper (lucide-react).
//
// Single, consistent entry point for every icon in the app:
//   • name       — a Lucide icon name, TYPED against the ICON_REGISTRY
//                  below (typos are compile errors; autocomplete works).
//                  Only lucide-react icons live here — no mixing icon
//                  libraries (design-system rule).
//   • size       — number (px, width = height) OR one of the semantic
//                  presets: "nav" (20, default) · "action" (24) ·
//                  "inline" (16).
//   • className  — passed straight to the underlying <svg>.
//
// Every icon renders with strokeWidth={1.5} (lucide's default is 2) so
// icons stay visually consistent at any size; the stroke scales with the
// icon (relative), which keeps proportions identical from a 16px inline
// chip to a 24px action button.
//
// The registry is an explicit allowlist (named imports → tree-shakeable,
// no runtime string→module lookup, no dynamic import flash). Adding an
// icon = one import + one registry line. It currently covers every icon
// imported anywhere in the app, so gradual migration is drop-in.
// ---------------------------------------------------------------------

