/** Type-safe icon name — pick from the registry (autocomplete + typos fail). */
export type IconName = keyof typeof ICON_REGISTRY;

/** Semantic size presets — nav 20px · action 24px · inline 16px. */
export const ICON_SIZES = {
  nav: 20,
  action: 24,
  inline: 16,
} as const;

export type IconSize = number | keyof typeof ICON_SIZES;

/** Uniform stroke width (lucide's default is 2) — set once, used everywhere. */
export const DEFAULT_ICON_STROKE_WIDTH = 1.5;

type IconProps = {
  /** Lucide icon to render (typed against the registry). */
  name: IconName;
  /** px size — number, or "nav" (20, default) · "action" (24) · "inline" (16). */
  size?: IconSize;
  className?: string;
} & Omit<LucideProps, "name" | "size">;

export function Icon({ name, size = "nav", className, ...rest }: IconProps) {
  const IconComponent = ICON_REGISTRY[name];
  const px = typeof size === "number" ? size : ICON_SIZES[size];

  // strokeWidth before {...rest} so an explicit override still wins.
  return (
    <IconComponent
      size={px}
      strokeWidth={DEFAULT_ICON_STROKE_WIDTH}
      className={className}
      {...rest}
    />
  );
}

export default Icon;
